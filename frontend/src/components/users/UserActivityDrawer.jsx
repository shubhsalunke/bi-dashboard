import React, { useState, useEffect, useCallback } from 'react';
import { X, RefreshCw, AlertCircle, Clock } from 'lucide-react';
import { usersApi } from '../../api/users.api';
import Badge from '../common/Badge';
import LoadingSkeleton from '../common/LoadingSkeleton';
import EmptyState from '../common/EmptyState';
import Pagination from '../common/Pagination';
import { formatDate } from '../../utils/format';
import { getRoleLabel } from '../../utils/userOptions';

const ACTION_LABELS = {
  USER_CREATED: { label: 'Account Created', variant: 'success' },
  USER_UPDATED: { label: 'Profile Updated', variant: 'primary' },
  USER_ROLE_CHANGED: { label: 'Role Changed', variant: 'warning' },
  USER_PASSWORD_RESET: { label: 'Password Reset', variant: 'warning' },
  USER_ACTIVATED: { label: 'Account Activated', variant: 'success' },
  USER_DEACTIVATED: { label: 'Account Deactivated', variant: 'danger' },
  USER_DELETED: { label: 'Account Deleted', variant: 'danger' },
  USER_LOGIN: { label: 'Signed In', variant: 'primary' },
};

const formatDetailsText = (log) => {
  if (!log.details || typeof log.details !== 'object') return null;
  const d = log.details;
  if (log.action === 'USER_ROLE_CHANGED' && d.previousRole && d.newRole) {
    return `${getRoleLabel(d.previousRole)} -> ${getRoleLabel(d.newRole)}`;
  }
  if (log.action === 'USER_UPDATED' && Array.isArray(d.updatedFields)) {
    return `Updated fields: ${d.updatedFields.join(', ')}`;
  }
  if (log.action === 'USER_PASSWORD_RESET' && d.method) {
    return d.method === 'temporary_password'
      ? 'Temporary password generated by admin'
      : 'Password updated from user edit modal';
  }
  if (log.action === 'USER_CREATED' && d.role) {
    return `Role: ${getRoleLabel(d.role)}${d.department ? ` | Dept: ${d.department}` : ''}`;
  }
  if (log.action === 'USER_LOGIN' && d.role) {
    return `Signed in as ${getRoleLabel(d.role)}`;
  }
  return JSON.stringify(d);
};

export const UserActivityDrawer = ({ isOpen, user, onClose }) => {
  const [logs, setLogs] = useState([]);
  const [userDetail, setUserDetail] = useState(user);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [pagination, setPagination] = useState({ page: 1, limit: 20, total: 0, totalPages: 1 });

  const loadActivity = useCallback(
    async (page = 1) => {
      if (!user?.id) return;
      setLoading(true);
      setError('');
      try {
        const res = await usersApi.getUserActivity(user.id, { page, limit: 20 });
        setLogs(res.data || []);
        if (res.user) setUserDetail(res.user);
        if (res.pagination) setPagination(res.pagination);
      } catch (err) {
        setError(err?.message || 'Failed to load user activity');
      } finally {
        setLoading(false);
      }
    },
    [user?.id]
  );

  useEffect(() => {
    if (isOpen && user?.id) {
      loadActivity(1);
    }
  }, [isOpen, user?.id, loadActivity]);

  useEffect(() => {
    if (!isOpen) return undefined;
    const handleKeyDown = (e) => {
      if (e.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isOpen, onClose]);

  if (!isOpen || !user) return null;

  const summary = userDetail || user;

  return (
    <div
      className="drawer-overlay"
      role="dialog"
      aria-modal="true"
      aria-labelledby="user-activity-title"
      onClick={(e) => {
        if (e.target === e.currentTarget) onClose();
      }}
    >
      <aside className="drawer-panel">
        <div className="drawer-header">
          <div>
            <h3 id="user-activity-title" className="modal-title">
              User Activity Log
            </h3>
            <div className="activity-meta">{summary.email}</div>
          </div>
          <div style={{ display: 'flex', alignItems: 'center', gap: 'var(--space-2)' }}>
            <button
              type="button"
              className="btn btn-secondary btn-sm"
              onClick={() => loadActivity(pagination.page)}
              disabled={loading}
              aria-label="Refresh activity log"
            >
              <RefreshCw size={13} aria-hidden="true" />
            </button>
            <button
              type="button"
              className="modal-close-btn"
              onClick={onClose}
              aria-label="Close activity drawer"
            >
              <X size={18} aria-hidden="true" />
            </button>
          </div>
        </div>

        <div className="drawer-body">
          <div className="activity-summary-card">
            <div
              style={{
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'space-between',
                gap: 'var(--space-2)',
                marginBottom: 'var(--space-2)',
              }}
            >
              <strong style={{ color: 'var(--text-primary)' }}>{summary.name}</strong>
              <div style={{ display: 'flex', gap: 6 }}>
                <Badge variant={summary.role}>{getRoleLabel(summary.role)}</Badge>
                <Badge status={summary.is_active ? 'active' : 'inactive'} />
              </div>
            </div>
            <div
              style={{
                display: 'grid',
                gridTemplateColumns: '1fr 1fr',
                gap: 'var(--space-2)',
                fontSize: '0.75rem',
                color: 'var(--text-secondary)',
              }}
            >
              <div>
                <span style={{ color: 'var(--text-muted)' }}>Last Login: </span>
                <span>
                  {summary.last_login_at
                    ? new Date(summary.last_login_at).toLocaleString()
                    : 'Never'}
                </span>
              </div>
              <div>
                <span style={{ color: 'var(--text-muted)' }}>Created: </span>
                <span>{formatDate(summary.created_at)}</span>
              </div>
            </div>
          </div>

          {loading ? (
            <LoadingSkeleton rows={5} columns={2} />
          ) : error ? (
            <EmptyState
              icon={AlertCircle}
              title="Unable to load activity"
              description={error}
              action={
                <button
                  type="button"
                  className="btn btn-secondary btn-sm"
                  onClick={() => loadActivity(pagination.page)}
                >
                  Retry
                </button>
              }
            />
          ) : logs.length === 0 ? (
            <EmptyState
              icon={Clock}
              title="No activity recorded yet"
              message="Account changes, role updates, password resets, and logins will appear here."
            />
          ) : (
            <div className="activity-timeline">
              {logs.map((log) => {
                const meta = ACTION_LABELS[log.action] || {
                  label: log.action,
                  variant: 'neutral',
                };
                const detailsText = formatDetailsText(log);

                return (
                  <div key={log.id} className="activity-item">
                    <div className="activity-item-top">
                      <Badge variant={meta.variant}>{meta.label}</Badge>
                      <span className="activity-meta tabular-nums">
                        {new Date(log.created_at).toLocaleString()}
                      </span>
                    </div>
                    {detailsText && (
                      <div style={{ fontSize: '0.8125rem', color: 'var(--text-primary)' }}>
                        {detailsText}
                      </div>
                    )}
                    <div className="activity-meta">
                      By: {log.user_email || 'System'}
                      {log.ip_address ? ` • IP: ${log.ip_address}` : ''}
                    </div>
                  </div>
                );
              })}
            </div>
          )}
        </div>

        {pagination.totalPages > 1 && (
          <div className="drawer-footer">
            <Pagination
              currentPage={pagination.page}
              totalPages={pagination.totalPages}
              totalItems={pagination.total}
              pageSize={pagination.limit}
              onPageChange={(p) => loadActivity(p)}
            />
          </div>
        )}
      </aside>
    </div>
  );
};

export default UserActivityDrawer;

